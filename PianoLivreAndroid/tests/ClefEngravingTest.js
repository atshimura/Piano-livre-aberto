"use strict";
const assert=require("assert");
const T=require("../app/src/main/assets/temporal-notation.js")._test;
let checks=0;
function eq(a,b,msg){
 checks++;
 assert(Math.abs(a-b)<1e-8,msg+": "+a+" !== "+b);
}
function ok(c,msg){checks++;assert(c,msg);}
// Test musical geometry, not just the presence of the SVG glyph.
const treble=T.clefAnchor(1,"G"),bass=T.clefAnchor(2,"F"),alto=T.clefAnchor(2,"C");
eq(treble.y,T.staffLineY(1,3),"G4 must be on row 3 from top");
eq(bass.y,T.staffLineY(2,1),"F3 must be on row 1 from top");
eq(alto.y,T.staffLineY(2,2),"C4 identifies the middle line");
ok(treble.midi===67&&bass.midi===53&&alto.midi===60,"MIDI landmark identities");
eq(T.pitchY({staff:1,clef:"G",step:"G",oct:4}),treble.y,"actual G4 head and clef coincide");
eq(T.pitchY({staff:2,clef:"F",step:"F",oct:3}),bass.y,"actual F3 head and clef coincide");
eq(T.pitchY({staff:2,clef:"C",step:"C",oct:4}),alto.y,"actual C4 head and clef coincide");
for(const [staff,sign] of [[1,"G"],[2,"F"],[1,"F"],[2,"G"],[1,"C"],[2,"C"]]){
 const landmark=T.clefAnchor(staff,sign);
 const step=sign==="G"?"G":sign==="F"?"F":"C",oct=sign==="G"?4:sign==="F"?3:4;
 eq(T.pitchY({staff,clef:sign,step,oct}),landmark.y,
    "landmark aligned even when a clef changes staff");
}
// SVG DOM stub measures actual group geometry generated by drawClef.
class Node {
 constructor(tag){this.tag=tag;this.attrs={};this.children=[];}
 setAttribute(k,v){this.attrs[k]=String(v);}
 appendChild(n){this.children.push(n);}
}
global.document={
 createElementNS:(ns,tag)=>new Node(tag)
};
const holder=new Node("svg");
const f=T.drawClef(holder,2,0,()=>60,"F");
ok(f.attrs["data-clef"]==="F","bass group is explicit");
ok(f.attrs["data-reference-midi"]==="53","F3 reference MIDI must be recorded");
eq(+f.attrs["data-reference-y"],bass.y,"F3 SVG ref y");
const dots=f.children.filter(n=>n.attrs["data-clef-dot"]);
ok(dots.length===2,"F clef has exactly two position-defining dots");
const above=dots.find(n=>n.attrs["data-clef-dot"]==="above");
const below=dots.find(n=>n.attrs["data-clef-dot"]==="below");
ok(!!above&&!!below,"both dots identified");
const localBass=bass.y-T.staffY(2);
eq(+above.attrs.cy,localBass-6.6,"upper dot half a staff spacing above F3");
eq(+below.attrs.cy,localBass+6.6,"lower dot half a spacing below F3");
eq((+above.attrs.cy + +below.attrs.cy)/2,localBass,"dots symmetrically straddle F3");
const g=T.drawClef(holder,1,0,()=>60,"G");
ok(g.attrs["data-clef"]==="G","G clef exists");
const gPath=g.children.find(n=>n.tag==="path");
ok(gPath&&gPath.attrs.d.length>180,"G clef must be an actual elaborated vector, not a typed character");
eq(+gPath.attrs["data-clef-coil-y"],treble.y-T.staffY(1),"G4 must be coil reference");
ok(!gPath.attrs.d.includes("NaN"),"G shape must be finite");
const clefMoved=T.drawClef(holder,1,8,beat=>beat*20,"F");
eq(+clefMoved.attrs["data-reference-y"],T.staffLineY(1,1),
   "mid-score F-clef change uses exact same anchor");
ok(holder.children.length===3,"all clefs rendered");
// Key signatures must remain on conventional pitches when a clef changes.
const gSharp=T.keySignatureNotes(2,"G"),fSharp=T.keySignatureNotes(2,"F");
ok(gSharp[0].step==="F"&&gSharp[0].oct===5,"first treble sharp marks F5 on top line");
eq(T.pitchY({staff:1,clef:"G",step:gSharp[0].step,oct:gSharp[0].oct}),
 T.staffLineY(1,0),"F5 key signature on top line");
ok(fSharp[0].step==="F"&&fSharp[0].oct===3,"first bass sharp marks F3");
eq(T.pitchY({staff:2,clef:"F",step:fSharp[0].step,oct:fSharp[0].oct}),
 T.staffLineY(2,1),"F3 sharp exactly on fourth line from bottom");
const bassFlat=T.keySignatureNotes(-1,"F")[0];
ok(bassFlat.step==="B"&&bassFlat.oct===2,"first bass flat B2");
eq(T.pitchY({staff:2,clef:"F",step:bassFlat.step,oct:bassFlat.oct}),
 T.staffLineY(2,3),"B2 bass flat must occupy second line from bottom");
const trebleFlat=T.keySignatureNotes(-1,"G")[0];
eq(T.pitchY({staff:1,clef:"G",step:trebleFlat.step,oct:trebleFlat.oct}),
 T.staffLineY(1,2),"B4 treble flat on middle line");
ok(T.keyDefaultAlter("F",1)===1 && T.keyDefaultAlter("B",-1)===-1 &&
 T.keyDefaultAlter("C",1)===0,"key signatures alter only their own pitch classes");
ok(T.writtenDuration({type:"quarter",dur:2/3})===1 &&
 T.writtenDuration({type:"half",dur:4/3})===2,
 "tuplets retain written symbolic type even with altered MIDI duration");

// The fixed rail must use the CURRENT clef, not the clef from beat zero.
const plan={
 clefs:[{staff:1,at:0,sign:"G"},{staff:2,at:0,sign:"F"},
  {staff:1,at:4,sign:"F"}]
};
const keyStart=new Node("svg");
T.drawKey(keyStart,0,1,()=>66,plan,0);
const before=keyStart.children.filter(n=>n.tag==="text");
ok(before.length===2,"key drawing creates two staff symbols");
eq(+before[0].attrs.y,T.staffLineY(1,0)+6,
 "G-clef first sharp F5 must be on top line before clef change");
const keyLater=new Node("svg");
T.drawKey(keyLater,0,1,()=>66,plan,5);
const after=keyLater.children.filter(n=>n.tag==="text");
eq(+after[0].attrs.y,T.staffLineY(1,1)+6,
 "after changing to F clef, first sharp must mark F3 on fourth line");
eq(+after[1].attrs.y,T.staffLineY(2,1)+6,
 "unchanged lower F-clef staff must remain on F3");

// Phrasing slurs are visually curved and must not be confused with ties.
const phrase=new Node("svg");
T.drawSlurs(phrase,[{
 staff:1,voice:"1",at:0,step:"C",oct:5,clef:"G",_stemUp:false,
 slur:[{number:"1",type:"start"}]
},{
 staff:1,voice:"1",at:2,step:"E",oct:5,clef:"G",_stemUp:false,
 slur:[{number:"1",type:"stop"}]
}],t=>40+t*60);
ok(phrase.children.length===1&&phrase.children[0].attrs["class"]==="temporal-slur",
 "slur start and stop should create one separate SVG curve");
ok(phrase.children[0].attrs.d.includes(" Q"),
 "slur should use a smooth quadratic arc");

// Rest symbols: whole hangs from the fourth line and half rests on the middle.
const wholeHolder=new Node("svg");
T.drawRest(wholeHolder,{staff:1,at:0,dur:4,type:"whole"},40);
const halfHolder=new Node("svg");
T.drawRest(halfHolder,{staff:1,at:0,dur:2,type:"half"},40);
const wholeRect=wholeHolder.children[0].children.find(x=>x.tag==="rect");
const halfRect=halfHolder.children[0].children.find(x=>x.tag==="rect");
ok(!!wholeRect&&!!halfRect,"both symbolic rests are rectangles");
eq(+wholeRect.attrs.y,T.staffLineY(1,1),"whole rest hangs below the fourth line");
eq(+halfRect.attrs.y+ +halfRect.attrs.height,T.staffLineY(1,2),
 "half rest sits directly on the middle line");
const tupletRest=new Node("svg");
T.drawRest(tupletRest,{staff:2,at:1,dur:4/3,type:"half"},60);
ok(tupletRest.children[0].children.some(n=>n.tag==="rect"),
 "half-rest symbol remains a half rest even when tuplet changes played length");

console.log("PASS ClefEngravingTest "+checks+
 " assertions: treble spiral aligns with G4, bass dots surround F3, C clef and clef changes stay on staff");
